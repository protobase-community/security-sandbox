-- The security sandbox's protected values, one kind per challenge level (README). The seed derives each from the
-- sandbox secret (seed/sandbox.ts), which never reaches the server.

-- Level 1: organizations are public, but the data config leaves out the token in the address suppliers mail their
-- invoices to.
alter table core.organizations add column inbox_token text;

-- Level 2: in the tenants' data config for the roles that screen tenants, on no screen.
alter table leasing.tenants add column internal_number text;

-- Level 3: a property's key safe and smart lock codes, revealed one at a time.
create table portfolio.access_codes (
  id bigint generated by default as identity primary key,
  organization_id integer not null references core.organizations (id),
  property_id bigint not null references portfolio.properties (id),
  kind text not null check (kind in ('key_safe', 'smart_lock')),
  code text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (property_id, kind)
);

create index access_codes_organization_idx on portfolio.access_codes (organization_id, created_at);
create index access_codes_property_idx on portfolio.access_codes (organization_id, property_id);
create index access_codes_kind_idx on portfolio.access_codes (organization_id, kind);

-- Level 4: a resource for admins with no screen.
create table core.integrations (
  id integer generated by default as identity primary key,
  organization_id integer not null references core.organizations (id),
  provider text not null,
  api_key text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (organization_id, provider)
);

-- Level 5: no resource reads this table.
create table core.webhook_secrets (
  organization_id integer not null references core.organizations (id),
  provider text not null,
  secret text not null,
  created_at timestamptz not null default now(),
  primary key (organization_id, provider)
);
